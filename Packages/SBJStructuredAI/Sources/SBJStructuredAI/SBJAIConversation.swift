import Foundation
import SBJStructure

/// The stable, application-facing facade while SBJStructuredAI is rebuilt.
/// This implementation does not load a model, perform discovery, or mutate data.
@MainActor
public final class SBJAIConversation<Root: SBJMutableStructure> {
    public private(set) var model: Root
    public private(set) var revision: String

    /// There is no runtime model in this stub. The property remains for clients
    /// that display availability, rather than assuming the engine is running.
    public static var isAvailable: Bool { false }

    public init(model: Root, revision: String = UUID().uuidString, instructions: String? = nil) {
        self.model = model
        self.revision = revision
    }

    /// Returns no structural results in the stub. No data is read or indexed.
    @discardableResult
    public func diagnoseTargets(for query: String) -> [String] { [] }

    public var discoveryDiagnostics: [String] { [] }

    /// Keeps the application's chat view functional without pretending AI ran.
    /// No proposal will be generated by this stub.
    public func send(_ text: String) async throws -> [SBJAIConversationEvent] {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw SBJAIConversationError.emptyMessage
        }
        try Task.checkCancellation()
        return [.text("SBJStructuredAI is currently a UI-only stub. No AI session is running and no document changes were made.")]
    }

    /// No proposals exist in the stub, so applying or rejecting one always fails.
    public func approve(_ proposalID: String) throws -> [SBJAIChangeResult] {
        throw SBJAIConversationError.unknownProposal
    }

    public func reject(_ proposalID: String) throws {
        throw SBJAIConversationError.unknownProposal
    }

    /// The host still controls which document instance and revision are current.
    public func replaceModel(_ updated: Root, revision newRevision: String) {
        model = updated
        revision = newRevision
    }
}
